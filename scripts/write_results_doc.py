"""Generate docs/08_results_baseline.md from the current data (deterministic baseline results).

Usage: python scripts/write_results_doc.py
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

from micp_lca import load_data, run_scenario
from micp_lca.benchmarks import compare_scenarios, compare_with_status_quo
from micp_lca.report import markdown_table

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "08_results_baseline.md"
CORE = ["GWP-total", "AP", "EP-freshwater", "EP-marine", "EP-terrestrial", "POCP", "ADP-fossil", "WDP"]
KEY = ["SP_lab_protocol_90d", "SP_optimised_recirculation", "SP_feather_media", "BC_lactate_30d", "BC_feather_media",
       "GYP_WCFC_single_dose", "GYP_WCFC_single_dose_feather", "GYP_HM2_single_dose", "TR_fungal_lactate", "ABIOTIC_WCFC_gypsum"]


def main() -> None:
    data = load_data()
    results = {n: run_scenario(n, data) for n in data.scenarios["scenarios"]}
    lines = ["# 8. Baseline results (deterministic, central values)", "",
             "Generated by `scripts/write_results_doc.py` from the current data files. Functional unit: 1 kg of dry",
             "product unless stated; modules A1–A3 (cradle-to-gate) and A1–A3 + C1–C4. EF 3.1 indicators.", ""]
    # per kg comparison
    per_kg = compare_scenarios(list(results.values()), data)
    per_kg = per_kg[per_kg["GWP-total A1-A3"].notna()].fillna({"fc_MPa": float("nan")})
    lines += ["## 8.1 Climate change per kg of product vs benchmarks", "",
              markdown_table(per_kg[["type", "GWP-total A1-A3", "GWP-total A1-A3+C", "fc_MPa", "bulk_density_kg_m3"]]), ""]
    # per m3
    res_m3 = {n: run_scenario(n, data, functional_unit="m3_product") for n in data.scenarios["scenarios"]}
    per_m3 = compare_scenarios(list(res_m3.values()), data, functional_unit="m3_product")
    per_m3 = per_m3[per_m3["GWP-total A1-A3"].notna()]
    lines += ["## 8.2 Climate change per m3 of product vs benchmarks", "",
              "Bulk densities: biocemented blocks 1100 kg/m3 (WCF) / 1250 kg/m3 (HM1, HM2); AAC 428–580; clay brick 575;",
              "adobe 1200; concrete block 2000; sand-lime brick 1800; WCF–OPC foamed block 801.", "",
              markdown_table(per_m3[["type", "GWP-total A1-A3", "GWP-total A1-A3+C", "fc_MPa"]], floatfmt=".4g"), ""]
    # core indicators for key scenarios
    rows = {}
    for n in KEY:
        r = results[n]
        t = r.totals(("A1", "A2", "A3"))
        rows[n] = {c: t[c] for c in CORE}
    df = pd.DataFrame(rows).T
    df.index.name = "scenario (A1–A3, per kg)"
    lines += ["## 8.3 Core EF 3.1 indicators of key scenarios (A1–A3, per kg product)", "",
              "Units: " + "; ".join(f"{c} [{data.category_unit(c)}]" for c in CORE), "",
              markdown_table(df, floatfmt=".3g"), "",
              "Coverage of the non-GWP categories is partly based on scaled proxy profiles (see docs/04_data_quality.md);",
              "AP and EP of the ureolytic scenarios are dominated by the directly modelled NH3/NH4+ emissions (native EF 3.1 factors).", ""]
    # contributions for two scenarios
    for n in ("GYP_WCFC_single_dose", "SP_lab_protocol_90d", "BC_lactate_30d"):
        r = results[n]
        g = r.by_group()[["GWP-total", "AP", "EP-terrestrial"]]
        g = g[(g.abs() > 1e-5).any(axis=1)]
        g.index.name = "process group"
        lines += [f"## 8.4 Contribution analysis — `{n}` (per kg product, A1–A3 + C + D)", "", markdown_table(g, floatfmt=".3g"), ""]
    # status quo comparison
    sq = compare_with_status_quo(results["GYP_WCFC_single_dose"], data)
    lines += ["## 8.5 System expansion: prototype block vs 'AAC block + landfilling of the absorbed fines' (GWP-total, kg CO2e per kg product, A1–A3 + C1–C4)", ""]
    lines += [f"- {k}: {v:.3f}" for k, v in sq.items()]
    lines += ["", "## 8.6 Reagent and mass balance diagnostics", ""]
    diag = []
    for n in KEY:
        m = results[n].meta
        diag.append({"scenario": n, "urea kg/kg solids": m["urea_kg_per_kg_solids"], "Ca mol/kg solids": m["ca_mol_per_kg_solids"],
                     "CaCO3 theoretical kg/kg": m["caco3_theoretical_kg_per_kg_solids"], "CaCO3 precipitated kg/kg": m["caco3_precipitated_kg_per_kg_solids"],
                     "precipitation efficiency": m["precipitation_efficiency"], "solution L/kg solids": m["liquid_to_solid_L_per_kg"],
                     "N hydrolysed kg/kg": m["n_hydrolysed_kg_per_kg_solids"], "carbonation uptake kg CO2/kg": m["carbonation_uptake_kg_per_kg_solids"],
                     "product kg/kg solids": m["product_kg_per_kg_solids"]})
    d = pd.DataFrame(diag).set_index("scenario")
    lines += [markdown_table(d, floatfmt=".3g"), ""]
    # Monte Carlo results, if the CLI has been run (results/mc_percentiles_<scenario>.csv, mc_spearman_<scenario>_GWP-total.csv)
    res_dir = ROOT / "results"
    mc_rows, sp_blocks = [], []
    for n in dict.fromkeys(KEY + ["SP_optimised_recirculation"]):
        pf = res_dir / f"mc_percentiles_{n}.csv"
        if pf.exists():
            pct = pd.read_csv(pf, index_col=0)
            g = pct.loc["GWP-total"]
            mc_rows.append({"scenario": n, "P2.5": g.iloc[0], "P25": g.iloc[1], "median": g.iloc[2], "P75": g.iloc[3], "P97.5": g.iloc[4],
                            "deterministic": results[n].gwp()})
            sf = res_dir / f"mc_spearman_{n}_GWP-total.csv"
            if sf.exists():
                sp = pd.read_csv(sf).head(6)
                sp_blocks.append(f"- `{n}`: " + "; ".join(f"{r['input'].replace('industrial.', '')} ({r['spearman_rho']:+.2f})" for _, r in sp.iterrows()))
    if mc_rows:
        d = pd.DataFrame(mc_rows).drop_duplicates("scenario").set_index("scenario")
        lines += ["## 8.7 Monte Carlo uncertainty (500 runs; GWP-total, kg CO2e per kg product, A1–A3)", "",
                  "Background factors: log-triangular between literature ranges or lognormal from pedigree scores (Ciroth et al. 2016);",
                  "foreground parameters: triangular between the ranges of scaleup.yaml. Medians exceed the deterministic values",
                  "because several literature ranges are right-skewed (e.g. tryptone 5–25 around 12 kg CO2e/kg).", "",
                  markdown_table(d, floatfmt=".3g"), "", "Most influential inputs (Spearman rank correlation with GWP-total):", ""]
        lines += sp_blocks + [""]
    # literature pathways and indicative cost
    from micp_lca.cost import cost_summary
    lit = [n for n in results if n.startswith("LIT_")]
    if lit:
        d = pd.DataFrame({n: {"GWP-total A1-A3": results[n].gwp(), "AP": float(results[n].totals(("A1", "A2", "A3"))["AP"]),
                              "EP-terrestrial": float(results[n].totals(("A1", "A2", "A3"))["EP-terrestrial"]),
                              "CaCO3 kg/kg solids": results[n].meta["caco3_precipitated_kg_per_kg_solids"],
                              "per kg CaCO3": run_scenario(n, data, functional_unit="kg_caco3_precipitated").gwp()} for n in lit}).T
        lines += ["## 8.8 Literature pathways modelled with the same framework (per kg product unless stated; industrial energy, 30 d)", "",
                  markdown_table(d, floatfmt=".3g"), "",
                  "Published values per kg CaCO3 (materials only): ureolysis 1.5–2.1 (Porter et al. 2021), 3.4 incl. fermenter (Deng et al. 2021),",
                  "carbonic anhydrase 0.56–0.67, sulfate reduction 1.4, denitrification 3.9, methane oxidation 1.2 (Porter et al. 2021).", ""]
    if not data.prices.empty:
        rows = []
        for n in dict.fromkeys(KEY + ["SP_optimised_recirculation"] + lit):
            cb, cl = cost_summary(results[n], data, "bulk"), cost_summary(results[n], data, "lab")
            rows.append({"scenario": n, "EUR/kg bulk grade": cb["total_A1-A3"], "EUR/kg laboratory grade": cl["total_A1-A3"],
                         "EUR/kg C1-C4": cb["total_C1-C4"], "GWP kg CO2e/kg": results[n].gwp()})
        d = pd.DataFrame(rows).drop_duplicates("scenario").set_index("scenario")
        lines += ["## 8.9 Indicative cost (A1–A3, priced inventory flows only; data/economics/prices.csv)", "",
                  markdown_table(d, floatfmt=".3g"), "",
                  "Labour, capital and margins are excluded. Laboratory-grade media and reagents multiply the cost by 4–5,",
                  "reproducing the observation of the papers that media dominate the cost of MICP (Omoregie et al. 2019; Ottová et al. 2026).", ""]
    lines += ["## 8.10 Interpretation", "",
              "* The ureolytic laboratory protocols are dominated by the nitrogen by-products (acidification, terrestrial",
              "  eutrophication) and by the fossil CO2 released from the 13-fold urea excess; even with stoichiometric dosing,",
              "  solution recirculation and ammonia stripping the route remains above 1 kg CO2e per kg of product because of",
              "  the cultivation medium (tryptone) and the calcium chloride.",
              "* The non-ureolytic Ca-lactate route avoids nitrogen emissions; its footprint is set by the media (LB/NB) and the",
              "  calcium lactate. Feather hydrolysate halves the cultivation burden.",
              "* The gypsum-promoted single-dose recipe (prototype blocks) needs ~0.4 L of suspension and 0.2 L of nutrient",
              "  solution per kg of solids only; its cradle-to-gate footprint (0.17 kg CO2e/kg; 0.09 with feather hydrolysate)",
              "  is below AAC (0.40–0.48 kg/kg) and the WCF–OPC foamed block (0.31), and comparable to fired clay brick per kg,",
              "  but per m3 it is only ~10 % below AAC and its strength (0.5–1.9 MPa) restricts it to non-load-bearing uses.",
              "* The abiotic control (gypsum + hydration only, 1.92 MPa) has the lowest footprint (0.03 kg CO2e/kg): for the",
              "  reactive WCF-C the bacteria act as a modifier, which the LCA reflects — the biological step must be justified",
              "  by durability or by the heterogeneous residues (HM1/HM2), where it is indispensable.",
              "* Laboratory equipment energy must never be used directly: it gives ~180 kg CO2e/kg.", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("written", OUT)


if __name__ == "__main__":
    main()
